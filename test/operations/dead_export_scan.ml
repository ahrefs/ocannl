(* gh-ocannl-806: a top-level helper in a module without an [.mli] is an exported value, even when
   its author meant it to be private. Two incidental hand sweeps found many such exports and still
   undercounted one family twofold. This repository scan makes the census mechanical for direct
   [*.ml] modules in [arrayjit/lib/], [tensor/] and (gh-ocannl-1009) [lib/], the user-facing half.

   The matching policy lives in [test/support/dead_export_scan.ml] and its synthetic negative
   controls. In particular, qualified paths through aliases count, and a bare identifier inside the
   lexical scope of [open M] counts conservatively. The latter can mistake a shadowing local for
   [M]'s value; that false-positive direction is deliberate for this first cut. An [include M] uses
   nothing (gh-ocannl-1085): it makes the including module a further receiver, so [Utils.v] counts
   for [Datatypes.v] -- but a value the include re-exports and nobody spells is dead, as
   [Datatypes.mutable_list] was for years behind [Utils]. Source-declared [let] values starting with
   [_] are deliberately unused by OCaml convention and excluded by policy. Values and modules
   generated by the [of_sexp], [sexp], [compare], [equal], [hash], [enumerate], [fields] and
   [variants] derivings are exports too (gh-ocannl-913); the matching expression extensions, and the
   calls other derivings generate, count as references to the same generated names, and a call
   another deriving of the defining module makes keeps a generated value alive exactly while the
   caller is (gh-ocannl-914). The [sexp_of] converters, derived or hand-written, are excluded by
   policy (the support module's header says why): they are the debugging and observability entry
   point, and [ppx_minidebug]'s typed log annotations consume them invisibly to a source-level
   census. Other PPX-generated values and values brought into the defining module by [include] are
   outside this source-level census.

   Types (gh-ocannl-1009) are censused by one conservative rule: a top-level type declaration in the
   same modules whose NAME is mentioned nowhere in the tree but its own declaration -- in no type
   path of any implementation or interface, and in no spelled value its deriving generates -- is
   reported. That is how [Train.example_train_result] would have been caught: it shipped for a year
   with its name in two proposals' prose and nowhere else. The rule's boundary is stated, not
   accidental. It is a name count, not a resolution: a record label or variant constructor is never
   resolved to its type, so a type used only through them reads as unmentioned (a loud false
   refusal, exempted with that reason), and any same-named type path anywhere credits it (a quiet
   false negative). Prose never mentions a type, so a stale doc comment cannot keep one alive.

   Every pre-existing zero-reference value is an exact [Module.value] exemption below, and every
   pre-existing unmentioned type an exact [Module.type_name] one. A new implicit export or
   unmentioned type fails rather than silently extending that baseline; an exemption that gains a
   reference also fails stale, so cleanup cannot leave a permanent hole. *)

